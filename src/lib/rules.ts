// Правила майданчика. Отруйні гриби й рослини продавати не можна — одне місце правди.
import { norm } from "./search";

const banned = ["мухомор", "поганка", "гриб", "грибы", "гриби", "блекота", "дурман", "болиголов", "беладона", "белладонна", "вовчі ягоди", "вороняче око", "борець", "аконіт", "чемериця"];

/** Повертає заборонене слово, якщо назва схожа на отруйне, інакше null. */
export function bannedWord(name: string): string | null {
  const n = norm(name);
  return banned.find((b) => n.includes(norm(b))) ?? null;
}

export const BANNED_TEXT = "Отруйні гриби й рослини (мухомори тощо) на Зборі продавати не можна.";
